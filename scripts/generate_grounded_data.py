calc_items = ["ジュース", "パン", "おにぎり", "りんご", "ノート", "コーヒー", "お菓子",
              "みかん", "卵", "牛乳", "アイス", "せんべい", "缶詰", "チョコレート"]
calc_questions = [
    "{price}円の{item}を{count}本買ったら合計いくら?",
    "{item}が1つ{price}円で、{count}個買うと合計いくらになる?",
    "{price}円の{item}、{count}個で合計はいくらになりますか?",
    "{item}を{count}個買いたいんだけど、1個{price}円だと全部でいくら?",
]

for _ in range(280):
    item = random.choice(calc_items)
    price = random.choice([50, 60, 80, 90, 100, 120, 130, 150, 180, 200, 220, 250, 280, 300, 350])
    count = random.choice([2, 3, 4, 5, 6, 7])
    q = random.choice(calc_questions).format(price=price, item=item, count=count)
    fact = try_calculate(q)
    if fact is None:
        continue
    a = random.choice(CALC_ANSWER_TEMPLATES).format(fact=fact)
    blocks.append(f"User: {q}(参考情報: {fact})\nLilas: {a}")

# お釣り・2品合計もまとまった量を確保
change_items = ["パン", "ノート", "コーヒー", "お菓子", "本"]
for _ in range(80):
    item = random.choice(change_items)
    price = random.choice([100, 150, 200, 250, 300, 350, 400, 450])
    pay = random.choice([500, 1000, 2000])
    if pay <= price:
        continue
    q = f"{item}を{price}円で買って、{pay}円を出したら、お釣りはいくら?"
    fact = try_calculate(q)
    if fact is None:
        continue
    a = random.choice(CALC_ANSWER_TEMPLATES).format(fact=fact)
    blocks.append(f"User: {q}(参考情報: {fact})\nLilas: {a}")

for _ in range(60):
    i1, i2 = random.sample(change_items, 2)
    p1 = random.choice([100, 150, 200, 250, 300])
    p2 = random.choice([100, 150, 200, 250, 300])
    q = f"{i1}が{p1}円で、{i2}が{p2}円のとき、合計いくらになる?"
    fact = try_calculate(q)
    if fact is None:
        continue
    a = random.choice(CALC_ANSWER_TEMPLATES).format(fact=fact)
    blocks.append(f"User: {q}(参考情報: {fact})\nLilas: {a}")

