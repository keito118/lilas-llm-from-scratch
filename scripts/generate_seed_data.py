"""
テンプレート+単語リストの組み合わせで、大量の会話データを合成生成するスクリプト。

v3: Lilasの人格を「秘書・アシスタント風の丁寧な話し方」に統一したので、
応答テンプレートはすべて「です/ます」調で書いている。

単純な「1トピック1応答」だと言い回しが単調になり、モデルが丸暗記しやすい
上に、似た文脈の話題(例: 疲れた/音楽の話)を混同しやすくなる。
そこで各カテゴリに「質問の言い回し違い」と「応答の言い回し違い」を複数用意し、
値ごとにランダムな組み合わせを複数生成することで、同じ話題でも表現の
バリエーションを増やしている。

使い方:
    python scripts/generate_seed_data.py
    -> index/generated_conversations_ja.txt を書き出す
"""

from __future__ import annotations

import random
from pathlib import Path

random.seed(42)

PROJECT_ROOT = Path(__file__).resolve().parent.parent
OUT_PATH = PROJECT_ROOT / "index" / "generated_conversations_ja.txt"

blocks: list[str] = []


def add(user: str, lilas: str) -> None:
    blocks.append(f"User: {user}\nLilas: {lilas}")


def add_multi(turns: list[tuple[str, str]]) -> None:
    lines = []
    for u, l in turns:
        lines.append(f"User: {u}")
        lines.append(f"Lilas: {l}")
    blocks.append("\n".join(lines))


def add_variety(
    values: list[str],
    question_templates: list[str],
    response_templates: list[str],
    per_value: int = 2,
) -> None:
    """values の各要素について、質問と応答の言い回しをランダムに組み合わせて
    per_value 個の会話を作る(同じ組み合わせが連続しないようにする)"""
    for value in values:
        combos = [(q, r) for q in question_templates for r in response_templates]
        random.shuffle(combos)
        for q_tmpl, r_tmpl in combos[:per_value]:
            add(q_tmpl.format(v=value), r_tmpl.format(v=value))


def add_fixed_variety(
    keys_to_responses: dict[str, list[str]],
    question_templates: list[str],
    per_key: int = 2,
) -> None:
    """キー(例: 感情の種類)ごとに専用の応答候補リストがある場合の生成"""
    for key, responses in keys_to_responses.items():
        combos = [(q, r) for q in question_templates for r in responses]
        random.shuffle(combos)
        for q_tmpl, r in combos[:per_key]:
            add(q_tmpl.format(v=key), r)


