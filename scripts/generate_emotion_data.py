for _ in range(90):
    n_filler = random.choice([3, 4, 5, 6])
    fillers = random.sample(FILLER_TURNS, k=n_filler)
    q, a = random.choice(FINAL_QA)
    lines = []
    for fu, fa in fillers:
        lines.append(f"User: {fu}")
        lines.append(f"Lilas: {fa}")
    lines.append(f"User: {q}")
    lines.append(f"Lilas: {a}")
    blocks.append("\n".join(lines))


def main() -> None:
    random.shuffle(blocks)
    text = "\n\n".join(blocks) + "\n"
    OUT_PATH.write_text(text, encoding="utf-8")
    print(f"書き出し: {OUT_PATH}")
    print(f"  例文数: {len(blocks)}")
    print(f"  文字数: {len(text):,}")


if __name__ == "__main__":
    main()
