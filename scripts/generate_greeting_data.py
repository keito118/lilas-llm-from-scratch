"""
挨拶・別れ際・相槌・お礼/謝罪への「場面に合った返し」を大量に学習させる
スクリプト。

2026-09-10、並列テストエージェントの調査で以下が判明した:
- 「こんにちは」等の開始挨拶が、対話用ファイル内では5〜9回しか
  「挨拶→挨拶の返し」として登場しない
- 同じ単語がWikipedia/instructコーパスでは「用件に答え始める」文脈
  (例:「こんにちは!以下は天気予報です…」)で2000回以上登場し、
  「挨拶に挨拶で返す」という対話的な意味づけが薄れている
- 結果として、「こんにちは」への応答が別れ際フレーズ(「今日もお話し
  できて楽しかったです」等)に化ける現象が観測された(再現率12.5%、
  広義の register-mismatchは62.5%)
- 「バイバイ」「ごめん」「すみません」も同様に対話ファイル内の出現数が
  極端に少なく(1回程度)、高い破綻率を示した

対策として、開始挨拶・別れ際・相槌・お礼/謝罪それぞれについて、
「場面に合った返し」の複数パターンを、対話データとして大量に(各カテゴリ
数十例)学習させる。これにより該当語の対話コンテキストでの出現数を
大幅に増やし、非対話コーパスの誤った連想を相対的に薄める。

使い方:
    python scripts/generate_greeting_data.py
    -> index/generated_greetings_ja.txt を書き出す
"""

from __future__ import annotations

import random
from pathlib import Path

random.seed(21)

PROJECT_ROOT = Path(__file__).resolve().parent.parent
OUT_PATH = PROJECT_ROOT / "index" / "generated_greetings_ja.txt"

blocks: list[str] = []

# ---- 1. 開始挨拶 → 挨拶の返し(絶対に別れ際フレーズを使わない) ----

OPENERS = {
    "こんにちは": [
        "こんにちは、今日はどうされましたか?",
        "こんにちは、お元気でしたか?",
        "こんにちは!今日も一日頑張りましょうね。",
        "こんにちは、何かお手伝いできることはありますか?",
        "こんにちは、良いお天気ですね。",
    ],
    "おはよう": [
        "おはようございます、今日も一日よろしくお願いいたします。",
        "おはようございます、よく眠れましたか?",
        "おはようございます!今日はどんな一日になりそうですか?",
        "おはようございます、素敵な朝ですね。",
    ],
    "こんばんは": [
        "こんばんは、今日も一日お疲れさまでした。",
        "こんばんは、今日はどんな一日でしたか?",
        "こんばんは、ゆっくりできていますか?",
    ],
    "やあ": [
        "こんにちは、お元気にされていましたか?",
        "やあ、どうされましたか?",
        "こんにちは、何かありましたか?",
    ],
    "もしもし": [
        "もしもし、Lilasです。聞こえていらっしゃいますか?",
        "もしもし、こんにちは。どうされましたか?",
        "はい、もしもし。ご用件を伺います。",
    ],
    "久しぶり": [
        "お久しぶりです、お元気にされていましたか?",
        "本当に久しぶりですね、お変わりありませんか?",
        "お久しぶりです!最近どうされていましたか?",
    ],
    "元気?": [
        "はい、元気にしております。あなたはいかがですか?",
        "元気ですよ、ありがとうございます。今日はどうされましたか?",
    ],
    "よっ": [
        "こんにちは、どうされましたか?",
        "はい、何かありましたか?",
    ],
}

for opener, replies in OPENERS.items():
    for reply in replies:
        blocks.append(f"User: {opener}\nLilas: {reply}")
        # 2ターン目も添えて、開始直後に続きの話題が来ても自然に繋がることを教える
        followups = [
            ("今日は天気がいいね", "それはいいですね、気持ちのよい一日になりそうですね。"),
            ("最近どう?", "おかげさまで変わりなく過ごしております。あなたはいかがですか?"),
            ("ちょっと聞いてほしいことがあるんだ", "はい、ぜひ聞かせてください。"),
        ]
        fu, fa = random.choice(followups)
        blocks.append(f"User: {opener}\nLilas: {reply}\n\nUser: {fu}\nLilas: {fa}")

# ---- 2. 別れ際 → 別れの挨拶(絶対に用件に答え始めない) ----

CLOSERS = {
    "バイバイ": ["バイバイ、良い一日を。", "はい、バイバイ。またお話しできるのを楽しみにしております。", "バイバイ、お元気で。"],
    "おやすみ": ["おやすみなさいませ。良い夢をご覧になれますように。", "おやすみなさい、ゆっくりお休みください。", "おやすみなさいませ、また明日お話ししましょう。"],
    "また今度": ["はい、また今度お話しいたしましょう。", "楽しみにしております、またお話ししましょうね。"],
    "じゃあね": ["はい、じゃあね。またお話しできるのを楽しみにしております。", "じゃあね、良い一日を過ごしてくださいね。"],
    "それじゃ": ["はい、それでは。またお話しできるのを楽しみにしております。"],
    "また明日": ["はい、また明日お話しいたしましょう。ゆっくりお休みください。"],
    "ありがとう、また今度話すね": ["こちらこそありがとうございました。またお話しできるのを楽しみにしております。"],
    "そろそろ寝るよ、おやすみ": ["はい、おやすみなさいませ。ゆっくりお休みください。"],
}

for closer, replies in CLOSERS.items():
    for reply in replies:
        blocks.append(f"User: {closer}\nLilas: {reply}")

# 別れの挨拶を会話の途中で検知できず続けようとする逆方向の失敗への対策:
# 何かの話題の後に別れの挨拶が来たとき、Lilasは新しい話題を振らずに
# きちんと会話を閉じる、という複数ターンの例を追加
CLOSING_AFTER_TOPIC = [
    (["最近映画を見に行ったんだ", "面白かったよ", "ありがとう、じゃあね"],
     ["それは楽しみですね、どんな映画だったのですか?",
      "それは良かったです!",
      "はい、こちらこそありがとうございました。またお話ししましょうね。"]),
    (["今日は買い物に行ってきたんだ", "いい買い物ができたよ", "そろそろ寝るね、おやすみ"],
     ["それは楽しみですね。",
      "それは良かったです、満足のいくお買い物になりましたね。",
      "はい、おやすみなさいませ。ゆっくりお休みください。"]),
    (["ちょっと相談したいことがあって", "うん、ありがとう助かった", "じゃあまたね"],
     ["はい、なんでしょうか。",
      "それは良かったです、お役に立てて嬉しいです。",
      "はい、またお話しできるのを楽しみにしております。"]),
]
for turns, replies in CLOSING_AFTER_TOPIC:
    lines = []
    for u, a in zip(turns, replies):
        lines.append(f"User: {u}")
        lines.append(f"Lilas: {a}")
    blocks.append("\n".join(lines))

# ---- 3. お礼・謝罪 → 別れ際フレーズに化けない、その場の反応 ----

THANKS_APOLOGY = {
    "ありがとう": ["どういたしまして、応援しております。", "いえいえ、お役に立てて嬉しいです。", "どういたしまして、いつでもお声がけください。"],
    "本当にありがとう": ["いえいえ、そんなに恐縮なさらないでくださいね。", "どういたしまして、お力になれて嬉しいです。"],
    "助かったよ、ありがとう": ["それは良かったです、お役に立てて何よりです。"],
    "ごめん": ["いえ、気になさらないでくださいね。", "いえいえ、大丈夫ですよ。", "そんなに謝らなくても大丈夫ですよ。"],
    "ごめんね、急に聞いちゃって": ["いえいえ、いつでも聞いてくださいね。"],
    "すみません": ["いえ、こちらは大丈夫ですので、気になさらないでくださいね。", "とんでもないです、お気になさらず。"],
    "すみません、お手数かけました": ["いえいえ、とんでもないです。お力になれて良かったです。"],
    "ちょっと変なこと言っちゃった、ごめん": ["いえ、そんなことはありませんよ。気になさらないでくださいね。"],
}
for u, replies in THANKS_APOLOGY.items():
    for reply in replies:
        blocks.append(f"User: {u}\nLilas: {reply}")

# ---- 4. 相槌・バックチャネル(既に比較的安定だが、量を補強) ----

BACKCHANNEL = {
    "うん": ["はい、続けてくださいね。", "うんうん、それで?"],
    "そうだね": ["そうですよね。", "はい、私もそう思います。"],
    "なるほど": ["そうなんですね。", "はい、勉強になります。"],
    "へえ": ["そうなんですよ、意外ですよね。", "はい、驚きですよね。"],
    "まじで": ["はい、本当なんですよ。", "そうなんです、驚きました。"],
}
for u, replies in BACKCHANNEL.items():
    for reply in replies:
        blocks.append(f"User: {u}\nLilas: {reply}")


def main() -> None:
    random.shuffle(blocks)
    text = "\n\n".join(blocks) + "\n"
    OUT_PATH.write_text(text, encoding="utf-8")
    print(f"書き出し: {OUT_PATH}")
    print(f"  例文数: {len(blocks)}")
    print(f"  文字数: {len(text):,}")


if __name__ == "__main__":
    main()
